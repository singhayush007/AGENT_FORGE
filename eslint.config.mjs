import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

/**
 * Architecture boundaries (see CLAUDE.md):
 *   app  ->  features  ->  shared
 * - shared/ never imports features/ or app/
 * - features/ never import app/, and import each other only along the explicit edges below
 *   (no cycles). Code needed by two features moves to shared/.
 */
const FEATURES = [
  "agents",
  "analytics",
  "auth",
  "builder",
  "dashboard",
  "landing",
  "playground",
  "runtime",
  "tools",
];

const ALLOWED_FEATURE_EDGES = {
  agents: ["auth", "playground"],
  analytics: ["auth"],
  builder: ["agents", "playground"],
  dashboard: ["agents", "auth"],
  landing: ["agents"],
  playground: ["auth"],
  runtime: ["tools"],
};

const restrict = (group, message) => ["error", { patterns: [{ group, message }] }];

const boundaryRules = [
  {
    files: ["shared/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-imports": restrict(
        ["@/features/*", "@/app/*"],
        "shared/ must not depend on features/ or app/."
      ),
    },
  },
  ...FEATURES.map((feature) => {
    const allowed = ALLOWED_FEATURE_EDGES[feature] ?? [];
    return {
      files: [`features/${feature}/**/*.{ts,tsx}`],
      rules: {
        "no-restricted-imports": restrict(
          [
            "@/app/*",
            ...FEATURES.filter((other) => other !== feature && !allowed.includes(other)).map(
              (other) => `@/features/${other}/*`
            ),
          ],
          `features/${feature} may not import other features (allowed: ${allowed.join(", ") || "none"}). Move shared code into shared/.`
        ),
      },
    };
  }),
];

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  ...boundaryRules,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by `prisma generate`
    "shared/lib/generated/**",
  ]),
]);

export default eslintConfig;
